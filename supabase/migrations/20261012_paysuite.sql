alter table public.companies
    add column if not exists status text not null default 'ACTIVE';

alter table public.companies
    add column if not exists expires_at timestamptz;

alter table public.companies add column if not exists owner_id uuid references auth.users(id);
alter table public.companies add column if not exists responsible_name text;
alter table public.companies add column if not exists admin_email text;
alter table public.companies add column if not exists phone text;
alter table public.companies add column if not exists plan_type text not null default 'BASIC';
alter table public.companies add column if not exists activation_code_hash text;
alter table public.companies add column if not exists activation_code_last4 text;

create unique index if not exists companies_activation_hash_uidx on public.companies(activation_code_hash) where activation_code_hash is not null;
alter table public.companies enable row level security;
drop policy if exists companies_owner_insert on public.companies;
drop policy if exists companies_owner_select on public.companies;
create policy companies_owner_insert on public.companies for insert to authenticated
    with check (owner_id = auth.uid() and status = 'PENDING' and expires_at is null and activation_code_hash is not null and plan_type in ('BASIC', 'PREMIUM'));
create policy companies_owner_select on public.companies for select to authenticated
    using (owner_id = auth.uid());

create table if not exists public.payments_log (
    id bigint generated by default as identity primary key,
    company_id text not null references public.companies(company_id),
    reference text not null,
    transaction_id text not null unique,
    status text not null,
    amount numeric(14, 2) not null check (amount >= 0),
    raw_payload jsonb not null default '{}'::jsonb,
    processed_at timestamptz,
    created_at timestamptz not null default now()
);

create index if not exists payments_log_company_idx
    on public.payments_log(company_id, created_at desc);

alter table public.payments_log enable row level security;
