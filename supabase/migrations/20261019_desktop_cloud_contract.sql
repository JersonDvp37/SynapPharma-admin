create or replace function public.desktop_tenant_exists(p_company_id text, p_pharmacy_id text)
returns boolean
language sql
security definer
stable
set search_path = public
as $$
    select exists (
        select 1
        from public.pharmacies p
        where p.company_id = p_company_id
          and p.pharmacy_id = p_pharmacy_id
    );
$$;

revoke all on function public.desktop_tenant_exists(text, text) from public;
grant execute on function public.desktop_tenant_exists(text, text) to anon, authenticated;

do $$
declare
    table_name text;
    table_names text[] := array[
        'cloud_produtos',
        'cloud_vendas',
        'cloud_estoque_movimentos',
        'cloud_usuarios',
        'cloud_audit_logs',
        'system_messages'
    ];
begin
    foreach table_name in array table_names loop
        execute format('drop policy if exists %I on public.%I', table_name || '_admin_select', table_name);
        execute format('drop policy if exists %I on public.%I', table_name || '_desktop_select', table_name);
        execute format('drop policy if exists %I on public.%I', table_name || '_desktop_insert', table_name);
        execute format('drop policy if exists %I on public.%I', table_name || '_desktop_update', table_name);
        execute format('drop policy if exists %I on public.%I', table_name || '_admin_insert', table_name);

        execute format(
            'create policy %I on public.%I for select to authenticated using (
                exists (
                    select 1 from public.companies c
                    where c.company_id = %I.company_id
                      and lower(c.admin_email) = lower(auth.jwt() ->> ''email'')
                )
            )',
            table_name || '_admin_select', table_name, table_name
        );
        if table_name = 'system_messages' then
            execute format(
                'create policy %I on public.%I for select to anon using (
                    (%I.recipient_pharmacy_id is not null and
                     public.desktop_tenant_exists(%I.company_id, %I.recipient_pharmacy_id))
                    or (%I.sender_pharmacy_id is not null and
                        public.desktop_tenant_exists(%I.company_id, %I.sender_pharmacy_id))
                )',
                table_name || '_desktop_select', table_name,
                table_name, table_name, table_name,
                table_name, table_name, table_name
            );
            execute format(
                'create policy %I on public.%I for insert to anon with check (
                    %I.sender_type = ''DESKTOP''
                    and %I.sender_pharmacy_id is not null
                    and public.desktop_tenant_exists(%I.company_id, %I.sender_pharmacy_id)
                )',
                table_name || '_desktop_insert', table_name,
                table_name, table_name, table_name, table_name
            );
            execute format(
                'create policy %I on public.%I for update to anon
                    using (public.desktop_tenant_exists(%I.company_id, %I.recipient_pharmacy_id))
                    with check (public.desktop_tenant_exists(%I.company_id, %I.recipient_pharmacy_id))',
                table_name || '_desktop_update', table_name,
                table_name, table_name, table_name, table_name
            );
            execute format(
                'create policy %I on public.%I for insert to authenticated with check (
                    exists (
                        select 1 from public.companies c
                        where c.company_id = %I.company_id
                          and lower(c.admin_email) = lower(auth.jwt() ->> ''email'')
                    )
                    and (%I.recipient_pharmacy_id is null or
                         public.desktop_tenant_exists(%I.company_id, %I.recipient_pharmacy_id))
                )',
                table_name || '_admin_insert', table_name,
                table_name, table_name, table_name, table_name
            );
        else
            execute format(
                'create policy %I on public.%I for select to anon using (
                    public.desktop_tenant_exists(%I.company_id, %I.pharmacy_id)
                )',
                table_name || '_desktop_select', table_name, table_name, table_name
            );
            execute format(
                'create policy %I on public.%I for insert to anon with check (
                    public.desktop_tenant_exists(%I.company_id, %I.pharmacy_id)
                )',
                table_name || '_desktop_insert', table_name, table_name, table_name
            );
            execute format(
                'create policy %I on public.%I for update to anon
                    using (public.desktop_tenant_exists(%I.company_id, %I.pharmacy_id))
                    with check (public.desktop_tenant_exists(%I.company_id, %I.pharmacy_id))',
                table_name || '_desktop_update', table_name, table_name, table_name, table_name, table_name
            );
        end if;
    end loop;
end
$$;

