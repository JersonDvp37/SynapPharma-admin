do $$
declare
    item record;
begin
    for item in
        select conrelid::regclass as table_name, conname
        from pg_constraint
        where contype = 'f'
          and confrelid = 'public.pharmacies'::regclass
          and conrelid::regclass::text in (
              'public.cloud_produtos', 'public.cloud_vendas',
              'public.cloud_estoque_movimentos', 'public.cloud_usuarios',
              'public.cloud_audit_logs', 'public.system_messages',
              'public.plans', 'public.payments_log'
          )
    loop
        execute format('alter table %s drop constraint %I', item.table_name, item.conname);
    end loop;
end
$$;

