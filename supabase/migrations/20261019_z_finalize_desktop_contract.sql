-- Reaplica a integridade para novos registros sem invalidar linhas legadas
-- que eventualmente ficaram órfãs durante as versões antigas do contrato.
do $$
declare
    table_name text;
    table_names text[] := array[
        'cloud_produtos', 'cloud_vendas', 'cloud_estoque_movimentos',
        'cloud_usuarios', 'cloud_audit_logs'
    ];
begin
    foreach table_name in array table_names loop
        if not exists (
            select 1 from pg_constraint
            where conrelid = ('public.' || table_name)::regclass
              and conname = table_name || '_pharmacy_id_fkey'
        ) then
            execute format(
                'alter table public.%I add constraint %I foreign key (pharmacy_id)
                 references public.pharmacies(pharmacy_id) on delete cascade not valid',
                table_name, table_name || '_pharmacy_id_fkey'
            );
        end if;
    end loop;
end
$$;

create or replace function public.desktop_tenant_exists(p_company_id text, p_pharmacy_id text)
returns boolean
language sql
security definer
stable
set search_path = public
as $$
    select exists (
        select 1 from public.pharmacies p
        where p.company_id = p_company_id
          and p.pharmacy_id = p_pharmacy_id
    );
$$;

create or replace function public.desktop_company_exists(p_company_id text)
returns boolean
language sql
security definer
stable
set search_path = public
as $$
    select exists (
        select 1 from public.companies c
        where c.company_id = p_company_id
    );
$$;

